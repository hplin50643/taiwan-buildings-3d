"""Verify current exterior WebP against historical renderer evidence and stored RGBA digests."""
import argparse, hashlib, io, json
from pathlib import Path
from PIL import Image
A=Path(__file__).resolve().parent

def sha(raw):
    return hashlib.sha256(raw).hexdigest()

def verify(root, rebuilt=None, camera=None):
    def load(p): return json.loads((root/p).read_bytes())
    d=load('display-proof.json')
    manifest={a['path']:a for a in load('qa/render-manifest.json')['files']}
    old=load('qa/isolated-rebuild.json')
    reopen=load('qa/render-reopen-validation.json')
    assert set(manifest)==set(d['exterior_webp_validation'])
    assert old['all_five_previews_identical'] is True
    for f,h in d['model_sha256'].items():
        assert sha((root/f).read_bytes())==h,f
    for f,h in old['delivered_generators_sha256'].items():
        assert sha((root/f).read_bytes())==h,f
    for path,x in d['exterior_webp_validation'].items():
        report=manifest[path]
        assert report['all_vertices_in_frame'] and report['sha256']==old['files_identical'][path]==x['historic_png_sha256'],path
        if path=='previews/front.png':
            assert reopen['scene_front_camera_reopen_render_exact'] and reopen['front_sha256']==x['historic_png_sha256']
        w=(root/x['webp']).read_bytes()
        assert len(w)==x['webp_bytes'] and sha(w)==x['webp_sha256'],path+' WebP file SHA256'
        with Image.open(io.BytesIO(w)) as im:
            assert im.format=='WEBP' and w[12:16]==b'VP8L' and not getattr(im,'is_animated',False)
            assert list(im.size)==x['dimensions']
            assert sha(im.convert('RGBA').tobytes())==x['decoded_rgba_sha256'],path+' decoded RGBA'
        if rebuilt is not None or camera is not None and path=='previews/front.png':
            f=(rebuilt/path) if rebuilt is not None else camera
            data=f.read_bytes()
            if rebuilt is not None:
                assert sha(data)==x['historic_png_sha256'],path+' fresh PNG byte SHA'
            with Image.open(io.BytesIO(data)) as im:
                assert list(im.size)==x['dimensions'] and sha(im.convert('RGBA').tobytes())==x['decoded_rgba_sha256'],path+' fresh RGBA'
    return len(manifest)

if __name__=='__main__':
    parser=argparse.ArgumentParser()
    parser.add_argument('--rebuilt',type=Path,help='Optional directory of PNGs generated by rebuild; not checked-in files')
    a=parser.parse_args()
    print(verify(A,a.rebuilt),'lossless WebP exterior views verified')
